export function getPlaceImage(name: string, rawUrl: string): string {
  // If rawUrl is a direct valid image URL from database, prioritize it
  if (rawUrl && (rawUrl.startsWith('http://') || rawUrl.startsWith('https://') || rawUrl.startsWith('/static/'))) {
    return rawUrl;
  }
  const lower = name.toLowerCase();
  for (const [key, val] of Object.entries(LANDMARK_IMAGE_MAP)) {
    if (lower.includes(key)) {
      return val;
    }
  }
  return rawUrl || 'https://images.unsplash.com/photo-1599661046289-e31897846e41?q=80&w=800';
}
